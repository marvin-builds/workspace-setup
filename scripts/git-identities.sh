#!/bin/sh
# Writes one git identity file per GitHub owner, so the commit email follows
# the repo's remote (see home/dot_config/git/config.tmpl, which includes
# them with includeIf "hasconfig:remote.*.url:...").
#
#   <dest_dir>/.config/git/identities/.includes   included by
#       ~/.config/git/config: per owner, an includeIf of its identity file
#       for https://, git@ and ssh:// remotes, owner letters case-folded
#   <dest_dir>/.config/git/identities/<owner>     [user] email = <email>,
#       plus a .conflict include per other owner
#   <dest_dir>/.config/git/identities/.conflict   empty name and email
#
# <pairs> is the github_identities data: owner=email pairs separated by
# whitespace. Every pair is validated before anything is written or
# removed: the owner must be a valid GitHub login, unique (ignoring case),
# and the email a GitHub noreply address. Errors name the pair's position,
# never its text, since the output can end up in public CI logs. Files for
# owners not in <pairs> are removed; an empty <pairs> removes them all.
# Files whose content is already right are left alone, so a second run
# changes nothing.
#
# chezmoi calls this from home/.chezmoiscripts/ with its destination dir.
#
# Usage: scripts/git-identities.sh <dest_dir> <pairs>

set -eu

NOREPLY_RE='^[0-9]+[+][^@]+@users[.]noreply[.]github[.]com$'
# GitHub login: 1-39 letters, digits or single inner hyphens.
LOGIN_RE='^[A-Za-z0-9]+(-[A-Za-z0-9]+)*$'

die() {
    printf 'git-identities: %s\n' "$*" >&2
    exit 1
}

[ $# -eq 2 ] || {
    printf 'usage: %s <dest_dir> <pairs>\n' "$(basename "$0")" >&2
    exit 2
}
dest=$1
pairs=$2
[ -d "$dest" ] || die "destination dir does not exist"
dir="$dest/.config/git/identities"

matches() {
    printf '%s\n' "$1" | grep -Eq -- "$2"
}

# ------------------------------------------------------------- validate

tab=$(printf '\t')
nl='
'
owners=   # " owner " list, in input order
seen=     # the same, lowercased, for the duplicate check
n=0
set -f
IFS=" $tab$nl"
# shellcheck disable=SC2086 # split the pairs on whitespace
set -- $pairs
unset IFS
set +f
for pair in "$@"; do
    n=$((n + 1))
    case $pair in
        *=*) ;;
        *) die "pair $n is not owner=email" ;;
    esac
    owner=${pair%%=*}
    email=${pair#*=}
    [ -n "$owner" ] || die "pair $n has an empty owner"
    [ -n "$email" ] || die "pair $n has an empty email"
    if [ ${#owner} -gt 39 ] || ! matches "$owner" "$LOGIN_RE"; then
        die "pair $n: owner is not a valid GitHub login"
    fi
    matches "$email" "$NOREPLY_RE" ||
        die "pair $n: email is not a GitHub noreply address (<id>+<login>@users.noreply.github.com)"
    lower=$(printf '%s' "$owner" | tr '[:upper:]' '[:lower:]')
    case $seen in
        *" $lower "*) die "pair $n repeats an owner of an earlier pair" ;;
    esac
    seen="$seen $lower "
    owners="$owners $owner "
done

# ---------------------------------------------------------------- write

mkdir -p "$dir"
tmp="$dir/.git-identities.$$"
trap 'rm -f "$tmp"' EXIT
trap 'exit 1' HUP INT TERM

CONFLICT=.conflict
INCLUDES=.includes
# The URL forms of a GitHub repo a remote can use.
FORMS='https://github.com/ git@github.com: ssh://git@github.com/'

# Remove files of owners no longer in the data (before writing, so a
# change of letter case works on case-insensitive file systems too).
for f in "$dir"/* "$dir"/.[!.]* "$dir"/..?*; do
    [ -e "$f" ] || [ -L "$f" ] || continue
    [ "$f" != "$tmp" ] || continue
    [ ! -d "$f" ] || [ -L "$f" ] || continue
    name=${f##*/}
    case $name in "$CONFLICT" | "$INCLUDES") continue ;; esac
    case $owners in
        *" $name "*) ;;
        *) rm -f "$f" ;;
    esac
done

# fold <owner>: the owner as a case-insensitive glob, each letter as a
# bracket class ([Oo][Cc]...), since GitHub logins ignore case and git's
# hasconfig patterns don't.
fold() {
    printf '%s\n' "$1" | awk '{
        for (i = 1; i <= length($0); i++) {
            c = substr($0, i, 1)
            u = toupper(c)
            l = tolower(c)
            if (u != l) printf "[%s%s]", u, l
            else printf "%s", c
        }
        printf "\n"
    }'
}

# include_if <owner> <file>: includeIf sections that include
# ~/.config/git/identities/<file> for a remote of <owner> in any URL form.
include_if() {
    folded=$(fold "$1")
    for form in $FORMS; do
        printf '[includeIf "hasconfig:remote.*.url:%s%s/**"]\n' "$form" "$folded"
        printf '\tpath = ~/.config/git/identities/%s\n' "$2"
    done
}

# includes <pair...>: the file ~/.config/git/config includes: each owner's
# identity file for a remote of that owner.
includes() {
    printf '%s\n' '# Generated by scripts/git-identities.sh from github_identities.'
    for pair in "$@"; do
        include_if "${pair%%=*}" "${pair%%=*}"
    done
}

# identity <owner> <escaped email> <pair...>: the content of <owner>'s
# identity file. The email is quoted, so no character of it can start a
# comment or end the value. A remote of any other owner includes
# .conflict, which empties name and email, so a repo with remotes of two
# owners refuses to commit instead of picking one. This include is nested
# here because it needs both conditions: a remote of <owner> (which
# included this file) and one of the other owner.
identity() {
    self=$1
    printf '[user]\n\temail = "%s"\n' "$2"
    shift 2
    for other in "$@"; do
        other=${other%%=*}
        [ "$other" != "$self" ] || continue
        include_if "$other" "$CONFLICT"
    done
}

conflict() {
    printf '%s\n' '# Included when a repo has remotes of two known owners: an empty' \
        '# name and email make git refuse to commit (see git-identities.sh).' \
        '[user]' '	name = ""' '	email = ""'
}

# put <file> <command...>: writes the command's output to <file> unless the
# file already holds exactly that. Compared before anything is created, so
# an unchanged run doesn't even touch the directory.
put() {
    target=$1
    shift
    if [ -f "$target" ] && [ ! -L "$target" ] && "$@" | cmp -s - "$target"; then
        return 0
    fi
    "$@" >"$tmp"
    rm -f "$target"
    mv "$tmp" "$target"
}

put "$dir/$CONFLICT" conflict
for pair in "$@"; do
    owner=${pair%%=*}
    email=$(printf '%s' "${pair#*=}" | sed 's/[\\"]/\\&/g')
    put "$dir/$owner" identity "$owner" "$email" "$@"
done
put "$dir/$INCLUDES" includes "$@"
